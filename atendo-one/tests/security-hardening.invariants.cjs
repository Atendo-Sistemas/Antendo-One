const fs = require('fs');
const server = fs.readFileSync('server.ts', 'utf8');
const api = fs.readFileSync('server/api.ts', 'utf8');
const restore = fs.readFileSync('ops/elolog-restore-verify.sh', 'utf8');
const pkg = JSON.parse(fs.readFileSync('package.json', 'utf8'));
if (!server.includes('blockedUntil') || !server.includes('backoffMinutes')) throw new Error('PROGRESSIVE_RATE_LIMIT_MISSING');
if (!server.includes('requireHttps') || !server.includes('res.redirect(308')) throw new Error('HTTPS_ENFORCEMENT_MISSING');
if (!api.includes("auditAuthFailure(req, 'LOGIN_FAILED'") || !api.includes("auditAuthFailure(req, 'OTP_VERIFY_FAILED'")) throw new Error('AUTH_FAILURE_AUDIT_MISSING');
if (!restore.includes('ALLOW_RESTORE_VERIFY') || !restore.includes('dropdb --if-exists')) throw new Error('SAFE_RESTORE_PROCEDURE_MISSING');
if (pkg.overrides?.qs !== '6.16.0' || pkg.dependencies?.['sanitize-html'] !== '2.17.7') throw new Error('DEPENDENCY_HARDENING_MISSING');
console.log('SECURITY_HARDENING_INVARIANTS_OK');
