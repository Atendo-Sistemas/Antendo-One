const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const read = file => fs.readFileSync(path.resolve(__dirname, '..', file), 'utf8');
const api = read('server/api.ts');
const cap = JSON.parse(read('capacitor.config.json'));
const pkg = JSON.parse(read('package.json'));
assert.equal(cap.appId, 'br.com.atendo.one.motorista');
assert.equal(cap.webDir, 'dist');
assert.equal(cap.server.androidScheme, 'https');
assert.ok(pkg.scripts['cap:sync'] && pkg.scripts['android:build']);
assert.match(api, /kind: tokenKind/, 'push-token must store expo and fcm kinds');
assert.match(api, /fcm\.googleapis\.com\/v1\/projects/, 'FCM HTTP v1 delivery must exist');
assert.match(api, /apiRouter\.post\('\/mobile\/push-token'[\s\S]{0,300}role !== 'MOTORISTA' \|\| isTestOrDemoUser/, 'push-token must be real drivers only');
assert.match(read('server.ts'), /MOBILE_APP_ORIGINS/);
assert.match(api, /DRIVER_LOCATION_MIN_INTERVAL_MS/, 'location endpoint must be rate limited');
assert.match(api, /proximityAlertsEnabled !== true\) return res\.status\(403\)/, 'location requires opt-in');
assert.match(api, /if \(!enabled\) driver\.currentLocation = undefined/, 'opt-out must erase location');
console.log('ANDROID_DRIVER_APP_INVARIANTS_OK');
