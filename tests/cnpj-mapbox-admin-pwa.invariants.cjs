const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const api = fs.readFileSync(path.join(root, 'server/api.ts'), 'utf8');
const budget = fs.readFileSync(path.join(root, 'src/components/budgets/BudgetManager.tsx'), 'utf8');
const freight = fs.readFileSync(path.join(root, 'src/components/freight/FreightFormModal.tsx'), 'utf8');
const driver = fs.readFileSync(path.join(root, 'src/components/driver/DriverDashboard.tsx'), 'utf8');
const sw = fs.readFileSync(path.join(root, 'public/sw.js'), 'utf8');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'public/manifest.json'), 'utf8'));

const cnpjStart = api.indexOf("apiRouter.get('/clients/cnpj/:cnpj/lookup'");
const externalFetch = api.indexOf('https://publica.cnpj.ws/cnpj/', cnpjStart);
const storedLookup = api.indexOf("db.clients.find(client => client.cnpj === cnpj", cnpjStart);
assert.ok(storedLookup >= cnpjStart && storedLookup < externalFetch, 'CNPJ deve consultar o banco antes da fonte externa');
assert.match(api, /source: 'DATABASE'/);
assert.match(api, /source: 'EXTERNAL'/);
assert.match(api, /geocode-tracking/);
assert.match(api, /overview=full&geometries=geojson/);
assert.match(api, /geometry: route.geometry/);
assert.match(budget, /routeGeometry/);
assert.match(freight, /routeGeometry/);
assert.match(freight, /setOriginZip\(item.zipCode\)/);
assert.match(freight, /setDestNumber\(item.number\)/);
assert.match(driver, /navigator.geolocation.watchPosition/);
assert.match(driver, /api.updateFreightLocation/);
assert.match(driver, /elolog_gps_queue/);
assert.match(driver, /wakeLock/);
assert.match(driver, /GPS ativo/);
assert.match(api, /neighborhood: find\('neighborhood'\)/);
assert.match(api, /heading:/);
assert.match(api, /const budgetActor = .*SUPER_ADMIN/);
assert.match(api, /req.user\?\.role === 'SUPER_ADMIN' \? String\(req.query.tenantId/);
assert.equal(manifest.start_url, '/login');
assert.match(sw, /url\.pathname === '\/login' \? '\/login' : '\/'/);
