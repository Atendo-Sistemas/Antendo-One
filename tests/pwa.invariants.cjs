const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const sw = fs.readFileSync(path.resolve(__dirname, '../public/sw.js'), 'utf8');
const main = fs.readFileSync(path.resolve(__dirname, '../src/main.tsx'), 'utf8');
const server = fs.readFileSync(path.resolve(__dirname, '../server.ts'), 'utf8');
const manifest = JSON.parse(fs.readFileSync(path.resolve(__dirname, '../public/manifest.json'), 'utf8'));
const packageVersion = JSON.parse(fs.readFileSync(path.resolve(__dirname, '../package.json'), 'utf8')).version;
const appVersion = fs.readFileSync(path.resolve(__dirname, '../src/version.ts'), 'utf8').match(/APP_VERSION = 'v([^']+)'/)?.[1];
assert.equal(appVersion, packageVersion);
assert.ok(sw.includes(`CACHE_NAME = 'atendo-one-v${appVersion}'`), 'service worker cache must change with app version');
assert.match(sw, /skipWaiting/);
assert.match(sw, /clients\.claim/);
assert.match(sw, /pathname\.startsWith\('\/api\/'\)/);
assert.match(sw, /url\.pathname === '\/login' \? '\/login' : '\/'/);
assert.equal(manifest.start_url, '/login');
assert.match(main, /serviceWorker\.register\('\/sw\.js'\)/);
assert.match(server, /normalizedPath === '\/login'/, 'o fallback de produção deve reconhecer /login');
console.log('PWA_INVARIANTS_OK');
