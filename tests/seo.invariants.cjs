const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const server = read('server.ts');
const api = read('server/api.ts');
const db = read('server/db.ts');
const commercial = read('server/publicCommercialDefaults.ts');
const app = read('src/App.tsx');
const page = read('src/components/common/PublicContentPage.tsx');
const home = read('src/components/common/GuestInstitutionalPage.tsx');
const index = read('index.html');
const manifest = read('public/manifest.json');
const version = read('src/version.ts');

assert.match(server, /res\.status\(isKnownPublic \? 200 : 404\)/, 'Rotas públicas desconhecidas devem retornar 404 real.');
assert.match(server, /isNotFound \? `Página não encontrada/, 'SSR deve renderizar uma página de erro compreensível.');
assert.match(server, /isNotFound \|\| !seo\.allowIndexing/, 'Rotas desconhecidas devem receber noindex.');
assert.match(server, /publicCommercialDefaults|publicPath === 'elo-log'/, 'SSR deve conhecer a seção comercial.');
assert.match(server, /<lastmod>\$\{parsed\.toISOString\(\)\}<\/lastmod>/, 'Sitemap deve usar lastmod somente quando houver data válida.');
assert.match(server, /item\.slug === 'elo-log' \? section :/, 'Landing comercial deve ser publicada diretamente em \/elo-log.');
assert.match(server, /max-age=31536000, immutable/, 'Assets versionados devem ter cache imutável.');
assert.match(server, /https:\/\/off\.atendo\.log\.br/, 'CSP deve permitir somente a origem oficial do widget externo.');
assert.match(server, /frame-src 'self' https:\/\/off\.atendo\.log\.br/, 'CSP deve declarar a origem do frame do widget.');
assert.match(server, /sha256-b7b03057e94fe25acc9a10366b6cc21263896dd2ad2eac92946794b1306f9f6e/, 'Script inline de tema deve ser autorizado por hash específico.');
assert.doesNotMatch(server, /script-src[^;]*unsafe-inline/, 'CSP não deve habilitar scripts inline arbitrários.');
assert.match(db, /publicCommercialPages\(now\)/, 'Páginas comerciais devem ser semeadas de modo idempotente.');
assert.match(commercial, /publicPath: 'elo-log'/, 'Páginas comerciais devem usar seção própria.');
assert.ok((commercial.match(/commercialPage\(now/g) || []).length >= 10, 'Catálogo comercial deve possuir cobertura mínima de páginas.');
assert.match(api, /publicContentCanonical/, 'API deve devolver canonical para conteúdo público.');
assert.match(api, /publicContentBrand/, 'API deve normalizar o branding nos metadados públicos.');
assert.match(api, /requestedSection/, 'API deve validar a seção solicitada no detalhe público.');
assert.match(api, /publicPath: \(item as any\)\.publicPath/, 'Catálogo SEO deve informar publicPath à SPA.');
assert.match(app, /PublicContentIndexPage/, 'SPA deve possuir índice público de conteúdo e soluções.');
assert.match(app, /window\.location\.pathname === '\/elo-log'/, 'SPA deve abrir índice de soluções.');
assert.match(page, /aria-label="Breadcrumb"/, 'Páginas de conteúdo devem exibir breadcrumb.');
assert.match(home, /item\.publicPath === 'elo-log'/, 'Home deve apontar cada card para a seção correta.');
assert.match(index, /rel="icon" type="image\/svg\+xml" href="\/favicon\.svg"/, 'HTML deve referenciar o favicon oficial.');
assert.match(index, /defer src="https:\/\/off\.atendo\.log\.br\/webchat\/public\/widget\.js"/, 'Widget externo deve ser carregado de forma não bloqueante.');
assert.match(manifest, /"src": "\/icons\/atendo-one-192\.png"/, 'Manifesto deve usar o ícone PNG oficial do Atendo One.');
assert.match(manifest, /"src": "\/icons\/atendo-one-512\.png"/, 'Manifesto deve declarar o ícone grande do Atendo One.');
assert.match(version, /APP_VERSION = 'v1\.7\.\d+'/, 'Interface deve exibir a versão da release atual.');
console.log('SEO_INVARIANTS=PASS');
