const fs = require('node:fs');
const api = fs.readFileSync('server/api.ts', 'utf8');
const db = fs.readFileSync('server/db.ts', 'utf8');
const create = api.slice(api.indexOf("apiRouter.post('/expenses'"), api.indexOf("// Update report / change status / approve"));
if (!create.includes('freightId: freight?.id')) throw new Error('EXPENSE_FREIGHT_OPTIONAL_MAPPING_MISSING');
if (!create.includes("const freight = data.freightId ?")) throw new Error('EXPENSE_OPTIONAL_FREIGHT_LOOKUP_MISSING');
if (!create.includes('driverIsAuthorized')) throw new Error('EXPENSE_OPTIONAL_DRIVER_AUTHORIZATION_MISSING');
if (!create.includes("req.user.role !== 'MOTORISTA'")) throw new Error('EXPENSE_STANDALONE_DRIVER_POLICY_MISSING');
if (!api.includes("['EMPRESA_SUPER_ADMIN', 'ADMIN', 'SUPERVISOR', 'MOTORISTA'].includes(req.user.role)")) throw new Error('EXPENSE_ROLE_POLICY_MISSING');
if (!api.includes('await db.persistTripExpense(newReport)') || !api.includes('await db.persistTripExpense(updatedReport)')) throw new Error('EXPENSE_RELATIONAL_PERSISTENCE_MISSING');
if (!db.includes('INSERT INTO trip_expenses')) throw new Error('EXPENSE_RELATIONAL_UPSERT_MISSING');
