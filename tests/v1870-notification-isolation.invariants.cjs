const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = relative => fs.readFileSync(path.join(root, relative), 'utf8');
const api = read('server/api.ts');
const navbar = read('src/components/layout/Navbar.tsx');
const pushClient = read('src/services/pushClient.ts');

assert.match(api, /sendPushNotificationToUsers\(recipients: User\[\]/, 'Web Push deve receber destinatários explícitos');
assert.doesNotMatch(api, /sendPushNotificationToAll/, 'broadcast PWA global não pode existir');
assert.match(api, /allowedRecipients\.has\(subscriptionKey\)/, 'Web Push deve validar usuário e tenant da assinatura');
assert.match(api, /const sourceTenantId = typeof values\.tenantId === 'string'/, 'dispatch deve derivar o tenant da operação');
assert.match(api, /user\.tenantId === sourceTenantId/, 'dispatch deve bloquear destinatários de outros tenants');
assert.match(api, /const tenantId = user\.tenantId \|\| sourceTenantId \|\| null/, 'canal deve usar o tenant do destinatário');
assert.match(api, /const notificationWhatsAppTenantId = user\.role === 'SUPER_ADMIN' \? undefined : tenantId \|\| undefined/, 'Super Admin deve usar o canal global e empresas o próprio canal');
assert.match(api, /resolveWhatsAppConfig\(notificationWhatsAppTenantId\)/, 'WhatsApp deve resolver o canal por empresa');
assert.match(api, /const eligibleDrivers = \(targetedDriver \? \[targetedDriver\]/, 'frete direcionado deve notificar somente o motorista selecionado');
assert.match(api, /const driverCanReceiveFreightAlert = \(driver: Driver/, 'alertas devem ter regra central de elegibilidade');
assert.match(api, /driver\.status !== 'DISPONIVEL'/, 'motoristas indisponíveis não devem receber alertas');
assert.match(api, /link\.status === 'BLOQUEADO'/, 'vínculos bloqueados não devem receber alertas');
assert.match(api, /vehicle\.status !== 'ATIVO'/, 'veículos inativos não devem receber alertas');
assert.match(api, /driverCanReceiveFreightAlert\(driver, db\.users\.find/, 'filtro de elegibilidade deve ser aplicado antes do dispatch');
assert.match(api, /userNotifs = db\.notifications\.filter\(n => n\.userId === req\.user\?\.id && .*n\.tenantId === req\.user\?\.tenantId/, 'leitura interna deve validar o tenant');
assert.match(api, /if \(n\.userId === req\.user\?\.id && .*n\.tenantId === req\.user\?\.tenantId/, 'marcação em massa deve validar o tenant');
assert.match(navbar, /useRef<HTMLDivElement>\(null\)/, 'sino deve possuir referência do menu');
assert.match(navbar, /document\.addEventListener\('pointerdown', closeOnOutsidePointer\)/, 'clique externo deve fechar notificações');
assert.match(navbar, /aria-expanded=\{showNotifications\}/, 'sino deve expor estado aberto/fechado');
assert.match(navbar, /aria-label=\{showNotifications \? 'Fechar notificações' : 'Abrir notificações'\}/, 'sino deve alternar o rótulo');
assert.match(pushClient, /api\/push\/subscribe/, 'cliente deve registrar a assinatura PWA');
